import datetime as dt

FA = '۰۱۲۳۴۵۶۷۸۹'
MONTHS = ['فروردین', 'اردیبهشت', 'خرداد', 'تیر', 'مرداد', 'شهریور', 'مهر', 'آبان', 'آذر', 'دی', 'بهمن', 'اسفند']


def fa(s) -> str:
    return str(s).translate({ord(str(i)): FA[i] for i in range(10)})


def to_jalali(g: dt.date):
    gy, gm, gd = g.year, g.month, g.day
    g_d_m = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
    gy2 = gy + 1 if gm > 2 else gy
    days = 355666 + 365 * gy + (gy2 + 3) // 4 - (gy2 + 99) // 100 + (gy2 + 399) // 400 + gd + g_d_m[gm - 1]
    jy = -1595 + 33 * (days // 12053)
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm, jd = 1 + days // 31, 1 + days % 31
    else:
        jm, jd = 7 + (days - 186) // 30, 1 + (days - 186) % 30
    return jy, jm, jd


def fmt_date(d: dt.datetime) -> str:
    jy, jm, jd = to_jalali(d.date())
    return fa(f'{jd} {MONTHS[jm-1]} {jy}')


def fmt_dt(d: dt.datetime) -> str:
    return fmt_date(d) + fa(f' — {d:%H:%M}')
